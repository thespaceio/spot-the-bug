#!/usr/bin/env node
// Prints the SQL that loads a team pack into the database.
//
// Team packs are snippets written for one client (their stack, their domain).
// They never go in this repository: keep the pack file somewhere private, then
//   node scripts/pack-sql.mjs path/to/pack.json > pack.sql
// and run pack.sql in the Supabase SQL editor (project "LureLens"). Then give
// the pack to a team with:
//   select arcade.grant_team_pack('team-slug', 'pack-id');
//
// Pack file: { "pack": { "id": "fintech-java-spring", "name": "...", "description": "..." },
//              "snippets": [ ...snippets in the same format as data/snippets/*.json... ] }
// The pack is checked with the same rules as the public snippets first, and
// nothing is printed if it fails. Snippets removed from the file are taken out
// of the pack (kept for old scores, no longer dealt). Safe to run again.
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/pack-sql.mjs path/to/pack.json > pack.sql');
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
try {
  execFileSync(process.execPath, [path.join(here, 'validate-snippets.mjs'), '--pack', file], { stdio: 'pipe' });
} catch (e) {
  console.error(String(e.stderr || e.message).split('\n').filter((l) => l.startsWith('error') || l.includes('problem')).join('\n'));
  console.error('The pack has problems (above). Nothing was printed.');
  process.exit(1);
}

const { pack, snippets } = JSON.parse(await readFile(file, 'utf8'));
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const rows = snippets.map((s) => `  (${q(s.id)}, ${q(pack.id)}, ${q(s.difficulty)}, ${json(s)}, true)`);
const keys = snippets.map((s) => {
  const accept = (s.acceptLines || []).map(Number).filter(Number.isInteger);
  return `  (${q(s.id)}, ${q(s.difficulty)}, ${q(s.surface || 'backend')}, ${q(s.category)}, ${Number(s.vulnerableLine)}, '{${accept.join(',')}}', ${q(pack.id)})`;
});
const ids = snippets.map((s) => q(s.id)).join(', ');

console.log(`-- Spot the Bug team pack "${pack.id}": ${snippets.length} snippets. Generated by scripts/pack-sql.mjs. Keep private.
begin;
insert into arcade.stb_packs (id, name, description) values (${q(pack.id)}, ${q(pack.name)}, ${q(pack.description || null)})
on conflict (id) do update set name = excluded.name, description = excluded.description, updated_at = now();

insert into arcade.stb_pack_snippets (id, pack, level, payload, active) values
${rows.join(',\n')}
on conflict (id) do update set pack = excluded.pack, level = excluded.level, payload = excluded.payload, active = true, updated_at = now();

update arcade.stb_pack_snippets set active = false, updated_at = now() where pack = ${q(pack.id)} and id not in (${ids});

insert into arcade.stb_answer_key (id, level, surface, category, vulnerable_line, accept_lines, pack) values
${keys.join(',\n')}
on conflict (id) do update set level = excluded.level, surface = excluded.surface, category = excluded.category,
  vulnerable_line = excluded.vulnerable_line, accept_lines = excluded.accept_lines, pack = excluded.pack, updated_at = now();
commit;`);
