#!/usr/bin/env node
// Prints SQL that copies every snippet's answer (level, kind of code, category, lines) into
// the online scoreboard's answer key, so the server can re-score posted games.
//
// Run after adding or editing snippets:
//   node scripts/answer-key-sql.mjs > answer-key.sql
// then paste the output into the Supabase SQL editor (project "LureLens",
// organization "Th3 SpaceIO") and run it. Safe to run any number of times.
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dataDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'data');
const readJson = async (rel) => JSON.parse(await readFile(path.join(dataDir, rel), 'utf8'));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const manifest = await readJson('manifest.json');
const rows = [];
for (const pack of manifest.packs) {
  const { snippets = [] } = await readJson(pack.file);
  for (const s of snippets) {
    const accept = (s.acceptLines || []).map(Number).filter(Number.isInteger);
    rows.push(`  (${q(s.id)}, ${q(s.difficulty)}, ${q(s.surface || 'backend')}, ${q(s.category)}, ${Number(s.vulnerableLine)}, '{${accept.join(',')}}')`);
  }
}

console.log(`-- Spot the Bug answer key: ${rows.length} snippets. Generated by scripts/answer-key-sql.mjs`);
console.log('insert into arcade.stb_answer_key (id, level, surface, category, vulnerable_line, accept_lines) values');
console.log(`${rows.join(',\n')}`);
console.log('on conflict (id) do update set level = excluded.level, surface = excluded.surface, category = excluded.category,');
console.log('  vulnerable_line = excluded.vulnerable_line, accept_lines = excluded.accept_lines, updated_at = now();');
